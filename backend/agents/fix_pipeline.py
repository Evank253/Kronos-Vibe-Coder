"""
End-to-end real-fix pipeline:
  scan/plan → apply locally (optional) → branch + commit + open PR on GitHub
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from .fix_agent import generate_fix_plan_for_path, apply_fix_plan, fixes_to_commit_changes
from .github_manager import create_branch, commit_changes, open_pull_request


def run_fix_pipeline(
    *,
    local_path: str,
    repo_full_name: Optional[str] = None,
    base_branch: str = "main",
    branch_name: Optional[str] = None,
    apply_locally: bool = True,
    open_pr: bool = True,
    token: Optional[str] = None,
    pr_title: Optional[str] = None,
    pr_body: Optional[str] = None,
) -> Dict[str, Any]:
    """
    1. Generate a real fix plan from local_path
    2. Optionally write fixes to disk
    3. If repo_full_name is set, create branch, commit real file contents, open PR
    """
    plan = generate_fix_plan_for_path(local_path)
    result: Dict[str, Any] = {
        "generated": datetime.now(timezone.utc).isoformat(),
        "plan": plan,
        "local_apply": None,
        "github": None,
    }

    if apply_locally and plan["fix_count"] > 0:
        result["local_apply"] = apply_fix_plan(plan, target_root=local_path)

    if not repo_full_name or plan["fix_count"] == 0:
        result["status"] = "plan_only" if plan["fix_count"] else "no_fixes"
        return result

    branch = branch_name or f"kronos/auto-fix-{datetime.now(timezone.utc).strftime('%Y%m%d-%H%M%S')}"
    branch_info = create_branch(repo_full_name, branch, base_branch=base_branch, token=token)
    changes = fixes_to_commit_changes(plan)
    commit_info = commit_changes(
        repo_full_name,
        branch,
        commit_message=f"fix: Kronos auto-fix ({plan['fix_count']} files)",
        changes=changes,
        token=token,
    )

    pr_info = None
    if open_pr:
        title = pr_title or f"Kronos auto-fix: {plan['fix_count']} file(s)"
        body = pr_body or (
            f"Automated fixes generated by Kronos-Vibe-Coder.\n\n"
            f"- Files changed: {plan['fix_count']}\n"
            f"- Syntax errors noted: {len(plan.get('syntax_errors') or [])}\n\n"
            f"Review carefully before merge."
        )
        pr_info = open_pull_request(
            repo_full_name,
            title=title,
            body=body,
            head=branch,
            base=base_branch,
            token=token,
        )

    result["github"] = {
        "branch": branch_info,
        "commit": commit_info,
        "pull_request": pr_info,
    }
    result["status"] = "committed_with_pr" if pr_info else "committed"
    return result
